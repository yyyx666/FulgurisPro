def check(condition: bool, what: str) -> bool:
    global OKS, MISSES
    if condition:
        OKS += 1
    else:
        MISSES += 1
    say(f"  {'OK  ' if condition else 'MISS'} {what}")
    return condition


def note_loading(key: str, what: str) -> None:
    """Record what a dump saw of the loading row, without calling it a failure.

    A dump is the wrong instrument for this one. While an indeterminate spinner animates the window
    never settles and uiautomator hands us the one underneath, so a dialog that is plainly waiting on
    screen reads as 'answered by the time we looked'. The shot taken at the same moment is the
    evidence, and `check_huge` is where we take one on purpose; here we only say what came back.
    """
    say(f"  {what}: a loading row in the dump = {SPINNERS.get(key, False)}")


def clip(text: str, width: int = 70) -> str:
    """Long enough to tell what a row holds, short enough to read in the report."""
    return text if len(text) <= width else text[:width] + "…"


def screen(serial: str) -> tuple[int, int]:
    """Logical screen size, cached: we need it on every tap."""
    if serial not in _SCREEN:
        _SCREEN[serial] = adb.screen_size(serial)
    return _SCREEN[serial]


def rows(serial: str) -> list[tuple[str, str]]:
    """(title, summary) of every row on screen, in dump order.

    Either one may be empty: a notice row carries no title, and the panel's database and cache rows
    carry no summary - the panel does not know what is inside them.
    """
    out: list[tuple[str, str]] = []
    title: str | None = None
    for node in adb.nodes(serial):
        if node.resource_id.endswith(":id/title"):
            if title is not None:
                out.append((title, ""))
            title = node.text or ""
        elif node.resource_id.endswith(":id/summary"):
            out.append((title or "", node.text or ""))
            title = None
    if title is not None:
        out.append((title, ""))
    return out


def list_items(serial: str) -> list[tuple[str, str]]:
    """(text1, text2) of the rows of the list dialog we have open.

    Our drill down lists are `simple_list_item_2` when they carry a value and `simple_list_item_1`
    when they do not, so a row may well have nothing for text2 - the add record one, say.
    """
    out: list[tuple[str, str]] = []
    pending: str | None = None
    for node in adb.nodes(serial):
        name = node.resource_id.split("/")[-1] if node.resource_id else ""
        if name == "text1":
            if pending is not None:
                out.append((pending, ""))
            pending = node.text or ""
        elif name == "text2" and pending is not None:
            out.append((pending, node.text or ""))
            pending = None
    if pending is not None:
        out.append((pending, ""))
    return out


def all_text(serial: str) -> list[str]:
    """Every piece of text on screen, wherever it sits: for the ones we cannot address by id."""
    return [node.text for node in adb.nodes(serial) if node.text]


# The three ids our table cells carry, see the list_item_storage_* layouts. A row is one kind of
# cell or another throughout: the head of a column, one record's cell, or the one cell of the row
# that adds a record.
TABLE_CELL_KINDS = {
    "storageHeaderCell": "header",
    "storageCell": "record",
    "storageActionCell": "action",
}


def table_bands(serial: str) -> list[tuple[str, list]]:
    """The records table as (kind, cells) rows, top to bottom, each cell its own node.

    Kind is 'header' for the row naming the columns, 'record' for one of the store's records and
    'action' for the single cell row that adds one. The cells come back in reading order: a dump
    lists them in no particular order, and a row's cells are grouped by the vertical band they
    share rather than by an exact y, a two line cell starting higher up than a one line one.

    The nodes themselves are what a tap needs. A cell says what it holds -- a column named `pad`
    heads cells also reading `pad` -- so finding one by its text would find the header first, and
    which cell we mean is only ever sayable by where it sits.
    """
    cells: list[tuple[int, int, int, str, object]] = []
    for node in adb.nodes(serial):
        kind = TABLE_CELL_KINDS.get(node.resource_id.split("/")[-1] if node.resource_id else "")
        if kind is None or not node.bounds:
            continue
        cells.append((node.bounds[1], node.bounds[3], node.bounds[0], kind, node))

    cells.sort(key=lambda cell: cell[:3])
    bands: list[list[tuple[int, int, int, str, object]]] = []
    for cell in cells:
        # Above the bottom of the row we are on: one more cell of it, rows never overlap
        if bands and cell[0] < max(other[1] for other in bands[-1]):
            bands[-1].append(cell)
        else:
            bands.append([cell])

    return [(band[0][3], [cell[4] for cell in sorted(band, key=lambda cell: cell[2])])
            for band in bands]


def table_rows(serial: str) -> list[tuple[str, list[str]]]:
    """The cell texts of every row of the table, as (kind, texts)."""
    return [(kind, [node.text or "" for node in cells]) for kind, cells in table_bands(serial)]


def table_records(serial: str) -> list[list]:
    """One list of cell nodes per record row, header and action rows left out."""
    return [cells for kind, cells in table_bands(serial) if kind == "record"]


def tap_table_cell(serial: str, row: int, column: int, what: str, wait: float = 1.5) -> bool:
    """Tap one cell of the records table by where it sits, not by what it says."""
    found = table_records(serial)
    if row >= len(found):
        say(f"  !! the table has no record row {row} to tap")
        return False
    cells = found[row]
    if column >= len(cells):
        say(f"  !! record {row} has only {len(cells)} columns, no column {column}")
        return False
    return tap_node(serial, cells[column], f"{what}, row {row} column {column}", wait=wait)


def tap_table_action(serial: str, wait: float = 1.5) -> bool:
    """Tap the one cell of the row that adds a record: it stands for no record, only itself."""
    found = next((cells for kind, cells in table_bands(serial) if kind == "action"), [])
    if not found:
        say(f"  !! no {ADD_RECORD!r} row to tap")
        return False
    return tap_node(serial, found[0], f"the {ADD_RECORD!r} row", wait=wait)


def long_press_table_row(serial: str, row: int, wait: float = 1.5) -> bool:
    """Hold one record row down, which is how the editor of the whole record opens.

    adb has no long press of its own: a swipe whose start and end are the same point, held longer
    than the platform's own threshold, is one. Nothing else here needs a hold, so it stays local
    rather than growing `adb.py` a helper for a single caller.
    """
    found = table_records(serial)
    if row >= len(found) or not found[row]:
        say(f"  !! the table has no record row {row} to hold down")
        return False
    node = found[row][0]
    if node.bounds is None:
        say(f"  !! record {row} has no bounds to hold down")
        return False
    x1, y1, x2, y2 = node.bounds
    x, y = (x1 + x2) // 2, (y1 + y2) // 2
    say(f"  hold record {row} down @({x},{y})")
    adb._adb(serial, ["shell", "input", "swipe", str(x), str(y), str(x), str(y), "1200"])
    time.sleep(wait)
    return True


def table_header(table: list[tuple[str, list[str]]]) -> list[str]:
    """The names the table heads its columns with, or [] when it drew no header at all."""
    return next((texts for kind, texts in table if kind == "header"), [])


def table_cells(table: list[tuple[str, list[str]]]) -> list[list[str]]:
    """One list of cell texts per record row of the table."""
    return [texts for kind, texts in table if kind == "record"]


def table_action(table: list[tuple[str, list[str]]]) -> list[str]:
    """The single cell of the row that adds a record, or [] when the table has no such row."""
    return next((texts for kind, texts in table if kind == "action"), [])


def table_texts(table: list[tuple[str, list[str]]]) -> list[str]:
    """Every cell of the table, header and action row included."""
    return [text for _, texts in table for text in texts]


def dump_table(serial: str, label: str, table: list[tuple[str, list[str]]], limit: int = 6) -> None:
    say(f"-- {label}")
    if not table:
        say("  !! no table")
    for kind, texts in table[:limit]:
        say(f"  {kind:<6} | " + " | ".join(clip(text, 24) for text in texts))
    if len(table) > limit:
        say(f"  ... and {len(table) - limit} more rows we did not print")


def wait_for_table(
    serial: str,
    matches,
    timeout: float = LEVEL_TIMEOUT,
    shot_name: str | None = None,
    spinner_key: str | None = None,
) -> list[tuple[str, list[str]]]:
    """The records table, waiting out the spinner for a row [matches] accepts.

    [matches] is given the cells of each row in turn, header and action row included, and the table
    comes back as soon as one of them satisfies it.

    Our levels only ask the page once the dialog is up, so the dialog opens on its loading row and
    the table arrives a moment later. Whether we caught that spinner is reported through [SPINNERS]:
    a level that answers before we look is one we have no proof was ever waiting.
    """
    deadline = time.time() + timeout
    caught = False
    while time.time() < deadline:
        if spinner_key and adb.find_node(serial, ":id/loadingProgress") is not None and not caught:
            caught = True
            SPINNERS[spinner_key] = True
            say(f"  OK   the dialog is up and still waiting for {clip(spinner_key)!r}")
            if shot_name:
                shot(serial, shot_name)
        table = table_rows(serial)
        if any(matches(texts) for _, texts in table):
            return table
        time.sleep(0.3)
    say(f"  !! no row we were waiting for after {timeout:.0f}s")
    dump_table(serial, "what we have instead", table_rows(serial))
    return table_rows(serial)


def enabled(serial: str, view_id: str) -> bool | None:
    """Whether one of our dialog's views can be used, or None when it is not on screen."""
    node = adb.find_node(serial, view_id)
    return None if node is None else node.enabled


