"""Exercise the storage panel: web storage, IndexedDB and the CacheStorage.

Opens a page, then from the console seeds a cookie, a storage item, an IndexedDB database holding
six object stores - one of them holding 500 records of about 2KB - and a cache holding two requests.
Walks to the Storage panel and checks that:

* the panel itself only reads names: it lists the database and the cache without saying what is
  inside them, and no storage item shows up as a row of its own;
* web storage items sit behind a "view items" row, which opens without waiting on the page;
* a store comes out as a table, one column per field its records have, one cell of it being one
  field of one record: a cell is edited on its own, the key of a store keeping its keys on the side
  renamed on its own, and a value that is not a plain object edited whole, each without leaving the
  panel, and each reading only the value it opens;
* the table of a store holding 500 records is read one page of 20 at a time, the buttons stepping
  through the pages in place;
* a record of two megabytes waits on a loading row that is caught in a screenshot, then shows in the
  table with only the beginning of its value: that one column opens an editor saying as much and
  cannot save, while the other columns of the very same record stay editable;
* the largest value our editor takes - a megabyte - is opened and timed on the way;
* a cache lists its requests with nothing to edit.

    python scripts/tools/repro_storage.py
    python scripts/tools/repro_storage.py --device SERIAL --url https://example.com
"""
