def run(serial: str, url: str) -> None:
    package = adb.detect_package(serial)
    say(f"=== {adb.device_label(serial)} [{package}] ===")

    adb.restart(serial, package)
    if not adb.settle(serial, package):
        say("  WARNING: not settled")
    adb.navigate(serial, package, url)

    say("-- seeding the page from the console")
    if not open_tab_item(serial, ":id/menuItemConsole", "Console"):
        return
    for what, code in (
        ("a cookie and a storage item", SETUP),
        (f"the {IDB_DB} database, {IDB_BULK}, {IDB_HUGE} and {IDB_WIDE} included", SEED_INDEXEDDB),
        (f"the {CACHE_NAME} cache", SEED_CACHE),
    ):
        say(f"  -- seeding {what}")
        say(f"    {clip(code, 300)}")
        if not type_code(serial, code):
            shot(serial, "seed_failed")
            return
    # IndexedDB and the CacheStorage writes are promises: the records want a moment to land
    time.sleep(4.0)
    leave_panel(serial)

    check_storage(serial)
    check_indexeddb(serial)
    check_caches(serial)
    check_huge(serial)
    check_wide(serial)
    check_cookies(serial)

    say(f"== {OKS} OK, {MISSES} MISS ==")


def main() -> int:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    parser.add_argument("--device", help="Target a specific adb device serial")
    parser.add_argument("--all", action="store_true", help="Act on all connected devices")
    parser.add_argument("--url", default="https://example.com", help="Page to open first")
    args = parser.parse_args()

    os.makedirs(OUT_DIR, exist_ok=True)
    for serial in adb.resolve_devices(args.device, args.all):
        run(serial, args.url)
        time.sleep(0.5)
        report = os.path.join(OUT_DIR, f"{serial.replace(':', '_')}-storage.txt")
        with open(report, "w", encoding="utf-8") as file:
            file.write("\n".join(REPORT) + "\n")
        print(f"report: {report}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
