def dialog_fields(serial: str) -> list[tuple[str, str, str, tuple]]:
    """(id, class, text, bounds) of every field and label in the dialog we have open."""
    out = []
    for node in adb.nodes(serial):
        name = node.resource_id.split("/")[-1] if node.resource_id else ""
        if name.startswith("cookie") or name.startswith("storageItem"):
            out.append((name, node.cls.split(".")[-1], node.text or "", node.bounds))
    return out


def dump_fields(serial: str) -> None:
    for name, cls, text, bounds in dialog_fields(serial):
        size = (bounds[3] - bounds[1]) if bounds else None
        say(f"  {name}: {cls} {clip(text)!r} h={size}")


def field_text_of(serial: str, view_id: str) -> str:
    """What one of our dialog fields holds, a field uiautomator reads as its hint when empty."""
    node = adb.find_node(serial, view_id)
    return (node.text if node else None) or ""


def type_into(serial: str, view_id: str, text: str) -> bool:
    """Replace the contents of one of our dialog fields.

    The keyboard comes down before we tap: tapping a field raises it, and it then covers the
    field below, so the next tap would land on a key and type into the field that still has
    focus. We read the field back afterwards because a value that never landed otherwise shows
    up much later, as a save the app refused for reasons that look like the app's own.

    The old contents go by selecting all of them and typing over the selection. [adb.clear_field]
    is not usable here: it clears with `input keyevent -n 160 67`, and on this device `-n` is not
    a repeat flag, so keycode 160 gets sent as well as 67 -- 160 moves focus to the next field and
    the DEL lands on nothing. That is invisible wherever the field starts empty, which is why the
    console seeds still look fine.
    """
    hide_ime(serial)
    if not tap_node(serial, adb.find_node(serial, view_id), view_id, wait=1.0):
        return False
    adb.key_combination(serial, adb.KEY_CTRL_LEFT, KEYCODE_A)
    adb.type_text(serial, text, wait=0.8)
    got = field_text_of(serial, view_id)
    if got != text:
        say(f"  MISS {view_id} holds {clip(got)!r} where we meant to type {clip(text)!r}")
        shot(serial, "type_failed")
        return False
    return True


def save_dialog(serial: str) -> bool:
    """Confirm the dialog we have open and say whether it took what we typed.

    Our write dialogs keep themselves open, and toast about it, when the input failed their own
    checks: a positive button still on screen after we press it means the app refused us.

    A save going to IndexedDB is a page script away: the dialog dismisses only once the page has
    reported its transaction done, which is as long as reading a value takes. So the button going
    away is something to wait for, not to look at once -- looking once calls a save the app is
    still making a refusal.
    """
    hide_ime(serial)
    if not tap_node(serial, adb.find_node(serial, ":id/button1"), "save button", wait=0.5):
        return False
    if not adb.wait_until(lambda: adb.find_node(serial, ":id/button1") is None, timeout=LEVEL_TIMEOUT):
        say("  MISS the dialog is still up: the app refused what we typed")
        shot(serial, "save_refused")
        return False
    return True


def open_tab_item(serial: str, view_id: str, what: str) -> bool:
    """Both panels are bottom sheets reached from the tab menu, next to Requests and Console."""
    tap_node(serial, adb.find_node(serial, ":id/button_more"), "button_more")
    if adb.find_node(serial, ":id/menuItemTabMenu") is not None:
        tap_node(serial, adb.find_node(serial, ":id/menuItemTabMenu"), "tab menu switcher")
    adb.wait_until(lambda: adb.find_node(serial, ":id/menuItemConsole") is not None, timeout=5)
    # The menu grows into place, its last entries arriving after the first ones
    adb.wait_until(lambda: adb.find_node(serial, view_id) is not None, timeout=3)
    node = find_menu_item(serial, view_id)
    if node is None:
        say(f"  !! {what} is not in the tab menu as it stands:")
        for other in adb.nodes(serial):
            if ":id/menuItem" in other.resource_id:
                say(f"    {other.resource_id.split('/')[-1]} {other.text!r} {other.bounds}")
        return False
    return tap_node(serial, node, what, wait=2.0)


def find_menu_item(serial: str, view_id: str, tries: int = 4):
    """A menu entry, scrolling the menu down for the ones below the fold.

    The menu is a drawer taller than the screen and the tab entries sit at its bottom: Cookies and
    Storage are both off screen until we drag it up.
    """
    for _ in range(tries):
        node = adb.find_node(serial, view_id)
        if node is not None:
            return node
        adb._adb(serial, ["shell", "input", "swipe", "2290", "1200", "2290", "700", "400"])
        time.sleep(0.8)
    return adb.find_node(serial, view_id)


def type_code(serial: str, code: str) -> bool:
    """Put one of our scripts in the console input and run it.

    The console keeps what the previous run left behind and our seeds run to hundreds of
    characters, so we empty it with a repeat count well past the shared helper's own, then read
    the field back: a seed that reached the device cut short is worse than one that never ran.
    """
    if not tap_node(serial, adb.find_node(serial, ":id/consoleInput"), "console input", wait=1.0):
        return False
    adb._adb(serial, ["shell", "input", "keyevent", "123"])  # KEYCODE_MOVE_END
    adb._adb(serial, ["shell", "input", "keyevent", "-n", "900", "67"])  # KEYCODE_DEL x900
    time.sleep(0.3)
    adb.type_text(serial, code, wait=1.0)

    field = adb.find_node(serial, ":id/consoleInput")
    got = (field.text if field else None) or ""
    if got != code:
        say(f"  MISS the console input holds {len(got)} characters, we typed {len(code)}")
        say(f"    got: {got!r}")
        return False

    return tap_node(serial, adb.find_node(serial, ":id/consoleRun"), "run button", wait=1.5)


def leave_panel(serial: str) -> None:
    """Back out of everything we opened: dialogs stack, the panel closes last."""
    for _ in range(6):
        if adb.find_node(serial, ":id/button_more") is not None:
            return
        adb.key(serial, adb.KEY_BACK, wait=1.2)


def open_storage_panel(serial: str) -> bool:
    if not open_tab_item(serial, ":id/menuItemStorage", "Storage"):
        return False
    adb.wait_until(lambda: bool(rows(serial)), timeout=5)
    return True


def wait_panel(serial: str, timeout: float = 10.0) -> float:
    """Wait for our categories to stop saying they are loading, and say how long that took.

    This used to be the whole problem: the panel read every record of every database before it
    showed anything, so on a page holding a lot of data it sat there for seconds.
    """
    started = time.time()
    while time.time() - started < timeout:
        page = rows(serial)
        if page and not any(summary == LOADING for _, summary in page):
            return time.time() - started
        if adb.find_node(serial, ":id/loadingProgress") is not None and "panel" not in SPINNERS:
            SPINNERS["panel"] = True
        time.sleep(0.2)
    say("  !! the panel is still saying it is loading")
    return time.time() - started


def wait_for_items(
    serial: str, needle: str, timeout: float = LEVEL_TIMEOUT, shot_name: str | None = None
) -> list[tuple[str, str]]:
    """The rows of the dialog we just opened, waiting out the spinner it comes up on.

    Our drill downs only ask the page once the dialog is up, so the dialog opens empty, with a
    spinner, and its rows land a moment later. Whether we caught that spinner is reported through
    [SPINNERS]: a level that answers before we look is a level we have no proof was ever waiting.
    """
    deadline = time.time() + timeout
    caught = False
    while time.time() < deadline:
        if adb.find_node(serial, ":id/loadingProgress") is not None:
            if not caught:
                caught = True
                SPINNERS[needle] = True
                say(f"  OK   the dialog is up and still waiting for {clip(needle)!r}")
                if shot_name:
                    shot(serial, shot_name)
        items = list_items(serial)
        if any(needle in text1 or needle in text2 for text1, text2 in items):
            return items
        time.sleep(0.3)
    say(f"  !! nothing holding {clip(needle)!r} after {timeout:.0f}s")
    dump_items(serial, "what we have instead")
    return list_items(serial)


def reopen_panel(serial: str) -> bool:
    """Back to a freshly opened panel: [collect_rows] leaves the old one scrolled to the bottom."""
    leave_panel(serial)
    return open_storage_panel(serial)


def open_records(serial: str, database: str, store: str) -> bool:
    """Walk the panel down to one object store's records, waiting each level out."""
    if not tap_row(serial, database):
        return False
    if not wait_for_items(serial, store):
        return False
    return tap_containing(serial, store)


def check_storage(serial: str) -> None:
    say("== storage panel ==")
    if not open_storage_panel(serial):
        return
    took = wait_panel(serial)
    say(f"-- the panel was done in {took:.2f}s, with {BULK_RECORDS} records of about "
        f"{BULK_PAD // 1024}KB seeded in a database of its own")
    shot(serial, "panel")

    found = collect_rows(serial)
    say("-- every row we walked past")
    for title, summary in found:
        say(f"  {clip(title)!r} | {clip(summary)!r}")

    check(not any(summary == LOADING for _, summary in found), "no category left saying it is loading")
    check(any(t == LOCAL and s == "1 " + ITEMS for t, s in found), f"{LOCAL} | 1 {ITEMS}")
    check(any(t == SESSION and s == "0 " + ITEMS for t, s in found), f"{SESSION} | 0 {ITEMS}")
    check(any(t.upper() == IDB.upper() and s == "1 " + DATABASES for t, s in found),
          f"{IDB} | 1 {DATABASES}")
    check(any(t == CACHES and s == "1 " + CACHES_UNIT for t, s in found), f"{CACHES} | 1 {CACHES_UNIT}")
    # Names only: what a database or a cache holds is not the panel's business any more
    check(any(t == IDB_DB and s == "" for t, s in found), f"a row for {IDB_DB!r}, without a summary")
    check(any(t == CACHE_NAME and s == "" for t, s in found),
          f"a row for {CACHE_NAME!r}, without a summary")
    # And the items themselves are not rows of the panel either
    check(not any(t == STORAGE_KEY for t, _ in found),
          f"no panel row for {STORAGE_KEY!r}: the items wait behind a tap")

    say("-- the items, behind their own row")
    if not reopen_panel(serial) or not tap_row(serial, BROWSE_ITEMS):
        leave_panel(serial)
        return
    items = wait_for_items(serial, STORAGE_KEY)
    # The items come out of the panel's own payload: no page round trip, no spinner to catch
    check(not SPINNERS.get(STORAGE_KEY, False), "the items opened without a spinner")
    check(any(t == STORAGE_KEY and s == STORAGE_VALUE for t, s in items),
          f"the {STORAGE_KEY!r} item and its value")
    shot(serial, "storage_items")
    if tap_containing(serial, STORAGE_KEY):
        dump_fields(serial)
        shot(serial, "storage_dialog")
    adb.key(serial, adb.KEY_BACK, wait=1.0)  # the editor
    leave_panel(serial)


def check_indexeddb(serial: str) -> None:
    say("== indexeddb ==")
    if not reopen_panel(serial):
        return

    say("-- drilling into our database")
    if not tap_row(serial, IDB_DB):
        leave_panel(serial)
        return
    stores = wait_for_items(serial, IDB_PEOPLE, shot_name="idb_stores_loading")
    shot(serial, "idb_stores")
    note_loading(IDB_PEOPLE, "the store list")
    check(any(t == f"{IDB_PEOPLE} — 2 {RECORDS}" for t, _ in stores),
          f"a store row {IDB_PEOPLE!r} | 2 {RECORDS}")
    check(any(t == f"{IDB_LOGS} — 1 {RECORDS}" for t, _ in stores),
          f"a store row {IDB_LOGS!r} | 1 {RECORDS}")
    check(any(t == f"{IDB_RAW} — 0 {RECORDS}" for t, _ in stores),
          f"a store row {IDB_RAW!r} | 0 {RECORDS}")
    check(any(t == f"{IDB_BULK} — {BULK_RECORDS} {RECORDS}" for t, _ in stores),
          f"a store row {IDB_BULK!r} | {BULK_RECORDS} {RECORDS}")
    check(any(t == f"{IDB_HUGE} — {HUGE_RECORDS} {RECORDS}" for t, _ in stores),
          f"a store row {IDB_HUGE!r} | {HUGE_RECORDS} {RECORDS}")
    check(any(t == f"{IDB_WIDE} — 1 {RECORDS}" for t, _ in stores),
          f"a store row {IDB_WIDE!r} | 1 {RECORDS}")

    say("-- drilling into one store")
    if not tap_containing(serial, IDB_PEOPLE):
        leave_panel(serial)
        return
    table = wait_for_table(serial, lambda texts: any(IDB_NAME_VALUE in cell for cell in texts))
    header = table_header(table)
    say(f"-- the table heads itself: {header}")
    check(header == ["id", "name"], "a column per field the record has, in the order it has them")
    check(any(len(cells) > 1 and cells[0] == IDB_NAME_KEY and cells[1] == IDB_NAME_CELL
              for cells in table_cells(table)),
          f"the {IDB_NAME_KEY} record holding {IDB_NAME_CELL}, as the JSON text of the field")
    shot(serial, "idb_records")

    # The columns of a store keeping its keys on the side are its fields, `id` first: what we tap is
    # one field of one record, and what it opens is that one field, nothing else
    say("-- one field of one record, on its own")
    if not tap_table_cell(serial, 0, 1, f"the {IDB_NAME_CELL} cell"):
        leave_panel(serial)
        return
    check(dialog_title(serial) == f"{IDB_PEOPLE} — name", "the editor names the field it edits")
    check(adb.find_node(serial, ":id/storageItemKey") is None,
          "no key box: the key is not what we came to edit")
    took = wait_value_ready(serial)
    say(f"-- the field editor had its value {took:.2f}s after we tapped it")
    dump_fields(serial)
    shot(serial, "idb_field_dialog")
    check(field_text_of(serial, ":id/storageItemValue") == IDB_NAME_CELL,
          f"the box holds that field as JSON text: {IDB_NAME_CELL}")
    check(enabled(serial, ":id/storageItemValue") is True, "the value box can be typed into")
    check(button_enabled(serial, "positive") is True, "and saved")
    check(adb.find_node(serial, ":id/storageItemNotice") is None, "with nothing said against it")
    if type_into(serial, ":id/storageItemValue", IDB_EDITED_CELL):
        check(save_dialog(serial), "the editor took the edited field")
    # The table behind the editor reads its store again, so the new value shows up in it, in the
    # one column we edited and no other
    edited = wait_for_table(serial, lambda texts: any(IDB_EDITED in cell for cell in texts))
    check(any(IDB_EDITED_CELL in cell for row in table_cells(edited) for cell in row),
          f"the edited field {IDB_EDITED_CELL} shows up in place")
    check(table_header(edited) == header and len(table_cells(edited)) == 2,
          "the record it belongs to kept its other columns and its key")
    shot(serial, "idb_records_edited")

    say("-- holding a record down, which opens the whole record as before")
    if long_press_table_row(serial, 1):
        check(field_text_of(serial, ":id/storageItemKey") == "2",
              "the key box holds the key of the record we held down")
        took = wait_value_ready(serial)
        dump_fields(serial)
        shot(serial, "idb_record_dialog")
        say(f"-- the whole record editor says {clip(dialog_title(serial))!r}, "
            f"its value ready {took:.2f}s after the hold")
        check(field_text_of(serial, ":id/storageItemValue") == BOB_RECORD,
              "and the value box holds the record whole, pretty printed")
        check(enabled(serial, ":id/storageItemKey") is False,
              "a store keeping its key path inside the value gives us no key to write")
        check(button_enabled(serial, "positive") is True, "the whole record is ours to save")
        check(button_enabled(serial, "neutral") is True, "deleting it still on offer")
        adb.key(serial, adb.KEY_BACK, wait=1.0)

    say("-- reading it back from a freshly opened panel")
    leave_panel(serial)
    if open_storage_panel(serial) and open_records(serial, IDB_DB, IDB_PEOPLE):
        reopened = wait_for_table(serial, lambda texts: any(IDB_EDITED in cell for cell in texts),
                                  timeout=LEVEL_TIMEOUT / 2)
        check(any(IDB_EDITED_CELL in cell for row in table_cells(reopened) for cell in row),
              f"the edited field {IDB_EDITED_CELL} sticks")

    say("-- adding a record to our hand keyed store")
    leave_panel(serial)
    if open_storage_panel(serial) and open_records(serial, IDB_DB, IDB_RAW):
        empty = wait_for_table(serial, lambda texts: texts == [ADD_RECORD])
        say(f"-- the table of the empty store heads itself: {table_header(empty)}")
        check(table_header(empty) == [KEY_COLUMN],
              f"a column for the keys, and none for a value yet: {table_header(empty)}")
        check(table_cells(empty) == [], "the empty store holds no record")
        check(table_action(empty) == [ADD_RECORD], "the row that adds a record, alone in its row")
        if tap_table_action(serial):
            dump_fields(serial)
            shot(serial, "idb_new_record_dialog")
            if type_into(serial, ":id/storageItemKey", NEW_RECORD_KEY):
                if type_into(serial, ":id/storageItemValue", NEW_RECORD_VALUE):
                    check(save_dialog(serial), "the editor took the new record")
            time.sleep(0.5)

        # A store without a key path gets a column of its own for the keys, and one for the value of
        # a record that is not a plain object: both are cells of their own, and edited one at a time
        added = wait_for_table(serial, lambda texts: texts[:1] == [NEW_RECORD_KEY])
        header = table_header(added)
        say(f"-- the table heads itself: {header}")
        check(header == [KEY_COLUMN, VALUE_COLUMN],
              f"a column for the keys and one for the value once a plain one is in there: {header}")
        check(any(cells[:2] == [NEW_RECORD_KEY, NEW_RECORD_VALUE] for cells in table_cells(added)),
              f"the new record {NEW_RECORD_KEY} -> {NEW_RECORD_VALUE}")

        say("-- the value column of that record, on its own")
        if tap_table_cell(serial, 0, 1, f"the {NEW_RECORD_VALUE} cell"):
            check(dialog_title(serial) == f"{IDB_RAW} — {VALUE_COLUMN}",
                  "the editor names the value as a whole")
            check(adb.find_node(serial, ":id/storageItemKey") is None,
                  "no key box: the value is what we came to edit")
            wait_value_ready(serial)
            dump_fields(serial)
            shot(serial, "idb_value_dialog")
            check(field_text_of(serial, ":id/storageItemValue") == NEW_RECORD_VALUE,
                  f"the box holds the whole value: {NEW_RECORD_VALUE}")
            check(button_enabled(serial, "positive") is True, "and it is ours to save")
            if type_into(serial, ":id/storageItemValue", EDITED_VALUE):
                check(save_dialog(serial), "the editor took the new value")
            time.sleep(0.5)

        say("-- the key column of the same record, which moves it without reading its value")
        named = wait_for_table(serial, lambda texts: texts[:2] == [NEW_RECORD_KEY, EDITED_VALUE])
        check(any(cells[:2] == [NEW_RECORD_KEY, EDITED_VALUE] for cells in table_cells(named)),
              f"the value column shows {EDITED_VALUE!r} where it showed {NEW_RECORD_VALUE!r}")
        if tap_table_cell(serial, 0, 0, f"the {NEW_RECORD_KEY} cell"):
            check(dialog_title(serial) == f"{IDB_RAW} — {KEY_COLUMN}", "the editor names the key")
            check(field_text_of(serial, ":id/storageItemKey") == NEW_RECORD_KEY,
                  f"the key box holds the key we tapped: {NEW_RECORD_KEY}")
            check(adb.find_node(serial, ":id/storageItemValue") is None,
                  "no value box: the key is what we came to change")
            dump_fields(serial)
            shot(serial, "idb_key_dialog")
            if type_into(serial, ":id/storageItemKey", RENAMED_KEY):
                check(save_dialog(serial), "the editor took the new key")
            time.sleep(0.5)
        moved = wait_for_table(serial, lambda texts: texts[:1] == [RENAMED_KEY])
        check(any(cells[:2] == [RENAMED_KEY, EDITED_VALUE] for cells in table_cells(moved)),
              f"the record moved to {RENAMED_KEY} taking its value with it: "
              f"{RENAMED_KEY} -> {EDITED_VALUE}")

    say(f"-- the big store: {BULK_RECORDS} records, read one page at a time")
    leave_panel(serial)
    if not open_storage_panel(serial) or not tap_row(serial, IDB_DB):
        leave_panel(serial)
        return
    if not wait_for_items(serial, IDB_BULK):
        leave_panel(serial)
        return
    if not tap_containing(serial, IDB_BULK):
        leave_panel(serial)
        return
    # Straight after the tap the dialog is up with the page still reading: this is what the user
    # sees while a large store is being opened
    note_loading(IDB_BULK, "the records dialog")
    page = wait_for_table(serial, lambda texts: texts[:1] == [str(BULK_FIRST_ID)],
                          shot_name="idb_bulk_loading", spinner_key=IDB_BULK)
    shot(serial, "idb_bulk_records")
    header = table_header(page)
    rows = table_cells(page)
    say(f"-- the table heads itself: {header}, over {len(rows)} records")
    check(header[:2] == ["id", IDB_BULK_FIELD], f"a column per field of the record: {header}")
    check(len(rows) == RECORDS_PAGE, f"one page of them, {len(rows)} records")
    check(max((len(cell) for row in rows for cell in row), default=0) <= MAX_CELL_CHARS,
          f"no cell longer than the {MAX_CELL_CHARS} characters we ask the page for")
    title = record_title(serial)
    say(f"-- the dialog describes itself as: {clip(title)!r}")
    check(page_range(1, RECORDS_PAGE) in title, "the title says which records we are showing")
    check(button_enabled(serial, "neutral") is False,
          "nothing to go back to from the first page")
    check(button_enabled(serial, "positive") is True, "the next page is ours to ask for")

    say(f"-- one {IDB_BULK_FIELD!r} cell of that page, on its own")
    if tap_table_cell(serial, 0, 1, f"the {IDB_BULK_FIELD} cell of the first record"):
        check(dialog_title(serial) == f"{IDB_BULK} — {IDB_BULK_FIELD}",
              "one cell of one record of a page of 500 opens that one field, not the record")
        took = wait_value_ready(serial)
        shown = field_text_of(serial, ":id/storageItemValue")
        say(f"-- the field editor had its {BULK_PAD} characters {took:.2f}s after we tapped the cell")
        check(shown == '"' + "x" * BULK_PAD + '"',
              f"the box holds the whole {BULK_PAD} character field, quotes and all")
        check(button_enabled(serial, "positive") is True,
              "a field this far under the cap is ours to save")
        shot(serial, "idb_bulk_field_dialog")
        tap_dialog_button(serial, "negative")
    # Opening a cell reads that one value, not the store again: the page we were on is still ours
    check(button_enabled(serial, "neutral") is False, "still on the first page after opening a cell")

    say("-- stepping to the next page")
    if not tap_dialog_button(serial, "positive"):
        leave_panel(serial)
        return
    page = wait_for_table(serial, lambda texts: texts[:1] == [str(RECORDS_PAGE)])
    rows = table_cells(page)
    shot(serial, "idb_bulk_page_two")
    check(any(cells[:1] == [str(RECORDS_PAGE)] for cells in rows),
          f"the page starts at record {RECORDS_PAGE}, where the last one left off")
    check(len(rows) == RECORDS_PAGE, f"a full page of them again, {len(rows)} records")
    title = record_title(serial)
    say(f"-- the dialog describes itself as: {clip(title)!r}")
    check(page_range(RECORDS_PAGE + 1, RECORDS_PAGE * 2) in title, "the title moved on with us")
    check(button_enabled(serial, "neutral") is True, "there is a way back from here")

    say("-- stepping back to the first page")
    if not tap_dialog_button(serial, "neutral"):
        leave_panel(serial)
        return
    page = wait_for_table(serial, lambda texts: texts[:1] == [str(BULK_FIRST_ID)])
    check(any(cells[:1] == [str(BULK_FIRST_ID)] for cells in table_cells(page)),
          "we are back where we started")
    check(button_enabled(serial, "neutral") is False, "and nothing to go back to again")

    leave_panel(serial)


def check_caches(serial: str) -> None:
    say("== cache storage ==")
    if not open_storage_panel(serial):
        return
    wait_panel(serial)
    found = collect_rows(serial)
    say("-- every row we walked past")
    for title, summary in found:
        say(f"  {clip(title)!r} | {clip(summary)!r}")
    check(any(t == CACHE_NAME and s == "" for t, s in found),
          f"a row for {CACHE_NAME!r}, without a summary")
    if not reopen_panel(serial):
        return
    shot(serial, "cache_panel")

    say("-- the cache's requests")
    if not tap_row(serial, CACHE_NAME):
        leave_panel(serial)
        return
    requests = wait_for_items(serial, CACHE_FIRST, shot_name="cache_requests_loading")
    note_loading(CACHE_FIRST, "the request list")
    check(any(CACHE_FIRST in t for t, _ in requests), f"a request for {CACHE_FIRST!r}")
    check(any(CACHE_SECOND in t for t, _ in requests), f"a request for {CACHE_SECOND!r}")
    # Read only: no way to write anything from here
    check(adb.find_node(serial, ":id/button1") is None, "no save button")
    check(not dialog_fields(serial), "no editable field")
    shot(serial, "cache_requests")

    adb.key(serial, adb.KEY_BACK, wait=1.0)
    leave_panel(serial)


def check_huge(serial: str) -> None:
    """The level that answers slowly enough to be caught in the act.

    Two megabytes per record: the one level slow enough that a shot taken straight after the tap
    finds the loading row still up, and the one holding a value well past what our editor takes. The
    shot is the evidence, not a dump: an indeterminate spinner means uiautomator never settles and
    what it hands us instead is the window underneath. So we shoot first and read the dump only
    afterwards, to see what the level ended up showing.

    The whole point of editing one column at a time comes out here: the column holding that value
    opens read only, while the rest of the record opens as any other.
    """
    say(f"-- the huge store: {HUGE_RECORDS} records of {HUGE_PAD // (1024 * 1024)}MB")
    if not open_storage_panel(serial):
        return
    if not tap_row(serial, IDB_DB):
        leave_panel(serial)
        return
    if not wait_for_items(serial, IDB_HUGE):
        leave_panel(serial)
        return
    # Hardly any wait after the tap: the read is the thing we are here to watch
    if not tap_containing(serial, IDB_HUGE, wait=0.1):
        leave_panel(serial)
        return
    shot(serial, "idb_huge_loading")
    say("  the shot above is where the loading row would show: check it by eye")
    # The field name is only ever in the header, so a table holding it cannot be the level underneath
    page = wait_for_table(serial, lambda texts: IDB_HUGE_FIELD in texts,
                          timeout=LEVEL_TIMEOUT * 2, spinner_key=IDB_HUGE)
    shot(serial, "idb_huge_records")
    rows = table_cells(page)
    check(len(rows) == HUGE_RECORDS, f"the huge store lists its {HUGE_RECORDS} records")
    check(max((len(cell) for row in rows for cell in row), default=0) <= MAX_CELL_CHARS,
          f"megabytes of a value still read in the table, {MAX_CELL_CHARS} characters at most")

    say(f"-- the {IDB_HUGE_FIELD!r} column, the one holding that value")
    if not tap_table_cell(serial, 0, 1, f"the {IDB_HUGE_FIELD} cell"):
        leave_panel(serial)
        return
    check(dialog_title(serial) == f"{IDB_HUGE} — {IDB_HUGE_FIELD}", "the editor names the field")
    wait_notice(serial)
    dump_fields(serial)
    shot(serial, "idb_huge_dialog")
    notice = adb.find_node(serial, ":id/storageItemNotice")
    say(f"-- the editor says: {clip((notice.text if notice else '') or '')!r}")
    check(bool(notice and notice.bounds), "the editor says the value is too large to edit here")
    check(enabled(serial, ":id/storageItemValue") is False, "the value box cannot be typed into")
    check(button_enabled(serial, "positive") is False, "the save button is disabled")
    # Deleting the record is the one thing worth doing with a value this size, and stays on offer
    check(button_enabled(serial, "neutral") is True, "deleting the record is still on offer")
    shown = field_text_of(serial, ":id/storageItemValue")
    check(len(shown) == MAX_VIEW_CHARS and set(shown) <= {'"', "y"},
          f"the box shows the beginning of the value instead, {len(shown)} characters of it")

    say("-- while the other column of that very record is ours to edit")
    adb.key(serial, adb.KEY_BACK, wait=1.0)
    if not tap_table_cell(serial, 0, 0, "the id cell of the same record"):
        leave_panel(serial)
        return
    check(dialog_title(serial) == f"{IDB_HUGE} — id", "the other column opens an editor of its own")
    took = wait_value_ready(serial)
    dump_fields(serial)
    shot(serial, "idb_huge_id_dialog")
    say(f"-- the id of that record was in the box {took:.2f}s after we tapped its cell")
    check(field_text_of(serial, ":id/storageItemValue") == "0",
          "holding the id of the record, with none of the value beside it")
    check(enabled(serial, ":id/storageItemValue") is True, "the id box can be typed into")
    check(button_enabled(serial, "positive") is True,
          "a record too big to open whole is still one we edit column by column")
    check(adb.find_node(serial, ":id/storageItemNotice") is None, "and nothing said against it")

    adb.key(serial, adb.KEY_BACK, wait=1.0)
    leave_panel(serial)


def check_wide(serial: str) -> None:
    """The largest value our editor still takes, and what opening it costs.

    [WIDE_PAD] is picked so that the JSON text of the value lands exactly on
    StorageFragment.VALUE_EDIT_MAX_CHARS: one character more and the editor would call it too large
    and refuse it. That cap is the one the user picked, and how long it takes to open is the number
    they asked to be told: a megabyte of text is a lot to lay out, and the cap it replaced was there
    for a reason.
    """
    say(f"-- the largest value we take: {VALUE_EDIT_MAX_CHARS // 1024}KB, one record holding it")
    if not open_storage_panel(serial):
        return
    if not tap_row(serial, IDB_DB):
        leave_panel(serial)
        return
    if not wait_for_items(serial, IDB_WIDE):
        leave_panel(serial)
        return
    if not tap_containing(serial, IDB_WIDE):
        leave_panel(serial)
        return
    page = wait_for_table(serial, lambda texts: IDB_WIDE_FIELD in texts,
                          timeout=LEVEL_TIMEOUT * 2, spinner_key=IDB_WIDE)
    shot(serial, "idb_wide_records")
    check(len(table_cells(page)) == 1, "the store holds the one record we seeded")

    say(f"-- opening its {IDB_WIDE_FIELD!r} cell, and timing how long the value takes to arrive")
    started = time.time()
    # The tap waits for nothing: the wait we are timing is the read behind the dialog, and a tap
    # that slept through it would be timing itself
    if not tap_table_cell(serial, 0, 1, f"the {IDB_WIDE_FIELD} cell", wait=0.0):
        leave_panel(serial)
        return
    took = wait_value_ready(serial, timeout=LEVEL_TIMEOUT * 2)
    say(f"-- a value of {VALUE_EDIT_MAX_CHARS} characters was in the box {took:.2f}s after the tap "
        f"({time.time() - started:.2f}s counting the two dumps around it)")
    shot(serial, "idb_wide_dialog")
    check(enabled(serial, ":id/storageItemValue") is True, "a value at the cap is still one we edit")
    check(button_enabled(serial, "positive") is True, "and one we can save")
    check(adb.find_node(serial, ":id/storageItemNotice") is None, "with nothing said against it")

    shown = field_text_of(serial, ":id/storageItemValue")
    say(f"-- the value box holds {len(shown)} characters")
    check(len(shown) == VALUE_EDIT_MAX_CHARS, "the whole value, not the beginning of it")
    check(shown.strip('"') == "z" * WIDE_PAD, "which is the string we seeded, quote to quote")

    adb.key(serial, adb.KEY_BACK, wait=1.0)
    leave_panel(serial)


